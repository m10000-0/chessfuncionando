// Para uma lista de lances UCI, retorna { bookPlies, name }: quantos lances iniciais são teoria e o nome mais específico.
export function identifyOpening(ucis) {
  let bookPlies = 0, name = null, nameLen = 0;
  for (const o of OPENINGS) {
    let k = 0;
    while (k < o.moves.length && k < ucis.length && o.moves[k] === ucis[k]) k++;
    if (k > bookPlies) bookPlies = k;
    if (k === o.moves.length && k >= nameLen) { name = o.name; nameLen = k; }
  }
  return { bookPlies, name };
}
